"""Update only clip and affected cord visualization in existing V3 scenes."""
import json,math
import trimesh
from build import ROOT,OUT,BOM,REVISION,save,export,write_bom
from model import Parameters,flexible_paths,plunger_pulley_path,polyline
source=OUT/'concepts/straight-arm-clip-45/clip.stl'
base=trimesh.load_mesh(source);base.apply_translation([0,0,-3]);base.export(OUT/'clip_string_guide.stl')
paths=[OUT/'manifest.json']+sorted(OUT.glob('*-*/manifest.json'))
changed=[]
for path in paths:
 data=json.loads(path.read_text())
 if data.get('version')!='v3' or not any(r.get('bom_id')=='clip_string_guide' for r in data.get('assembly',[])):continue
 p=Parameters(**data['parameters'])
 for row in data['assembly']:
  if row.get('bom_id')!='clip_string_guide':continue
  mesh=base.copy()
  if p.side=='far':mesh.apply_transform(trimesh.transformations.rotation_matrix(math.pi,[1,0,0]))
  index=int(row['name'].split('_')[-1])-1
  mesh.apply_translation([0,0,p.guide_stations[index]])
  mesh.export(path.parent/row['file'])
 string,bands,motion=flexible_paths(p)
 for name,points,diameter in [('twine',string,p.twine_diameter),('twine_phone',string[:len(string)-len(p.guide_stations)],p.twine_diameter),('band_overtravel',bands['band_overtravel'],1.4)]:
  row=next(r for r in data['assembly'] if r['name']==name)
  export(polyline(points,diameter),path.parent/row['file'])
 target=(p.first_guide[0]-p.phone_right,p.first_guide[1]-p.button_y,p.first_guide[2]-p.height)
 hp=[[p.point(q) for q in plunger_pulley_path((p.rest_gap+p.button_stroke)*i/20,target)] for i in range(21)]
 data['motion'].update(motion,string_points=string,band_paths=bands,head_paths=hp,twine_to_stop=sum(math.dist(a,b) for a,b in zip(hp[0],hp[0][1:]))-sum(math.dist(a,b) for a,b in zip(hp[-1],hp[-1][1:])))
 data['bom']=BOM;data['revision']=REVISION
 data['clip_guide_pose']='Approved manufactured open pose; closed TPU deformation not simulated.'
 save(path,data);changed.append(str(path.relative_to(ROOT)))
write_bom()
save(OUT/'clip-viewer-promotion.json',{'revision':REVISION,'source':str(source.relative_to(ROOT)),'updated_manifests':changed,'eye_center_y_mm':13.3,'limits':['Assembly displays approved open print pose, not simulated wrapped closure.','Historical print plates and assembly STEP not regenerated by viewer-only promotion.']})
print(changed)
